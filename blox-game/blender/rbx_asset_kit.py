def render_preview(obj, path, res=512):
    scene = bpy.context.scene
    scene.render.engine = "CYCLES"
    scene.cycles.device = "CPU"
    scene.cycles.samples = 24
    scene.render.resolution_x = scene.render.resolution_y = res
    scene.render.film_transparent = False
    scene.view_settings.view_transform = "Standard"

    world = bpy.data.worlds.new("World")
    world.use_nodes = True
    world.node_tree.nodes["Background"].inputs["Color"].default_value = (0.16, 0.18, 0.24, 1)
    world.node_tree.nodes["Background"].inputs["Strength"].default_value = 1.0
    scene.world = world

    sun = bpy.data.objects.new("Sun", bpy.data.lights.new("Sun", "SUN"))
    sun.data.energy = 3.5
    sun.rotation_euler = (math.radians(50), 0, math.radians(35))
    scene.collection.objects.link(sun)

    corners = [obj.matrix_world @ v.co for v in obj.data.vertices]
    lo = np.min(np.array(corners), axis=0)
    hi = np.max(np.array(corners), axis=0)
    center, size = (lo + hi) / 2, float(np.max(hi - lo))

    cam = bpy.data.objects.new("Cam", bpy.data.cameras.new("Cam"))
    cam.data.type = "ORTHO"
    cam.data.ortho_scale = size * 1.3
    direction = np.array([1.0, -1.4, 0.7])
    direction /= np.linalg.norm(direction)
    cam.location = tuple(center + direction * size * 3)
    look = center - np.array(cam.location)
    cam.rotation_euler = (math.atan2(math.hypot(look[0], look[1]), -look[2]), 0,
                          math.atan2(look[1], look[0]) - math.pi / 2)
    cam.data.clip_end = size * 10
    scene.collection.objects.link(cam)
    scene.camera = cam

    scene.render.filepath = path
    bpy.ops.render.render(write_still=True)


def export(obj, kind, out_dir):
    name = obj.name
    tris = tri_count(obj)
    dims = obj.dimensions
    budget = TRI_BUDGET[kind]
    status = "OK" if tris <= budget else f"OVER BUDGET ({budget})"

    bpy.ops.object.select_all(action="DESELECT")
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj
    bpy.ops.export_scene.fbx(
        filepath=os.path.join(out_dir, name + ".fbx"),
        use_selection=True,
        apply_unit_scale=True,
        apply_scale_options="FBX_SCALE_UNITS",
        axis_forward="-Z",
        axis_up="Y",
        use_mesh_modifiers=True,
        mesh_smooth_type="FACE",
        add_leaf_bones=False,
        path_mode="COPY",
        embed_textures=True,
    )
    render_preview(obj, os.path.join(out_dir, name + "_preview.png"))
    bpy.ops.wm.save_as_mainfile(filepath=os.path.join(out_dir, name + ".blend"), compress=True)
    print(f"[asset] {name:<26} tris={tris:<5} size={dims.x:.2f}x{dims.y:.2f}x{dims.z:.2f} studs  "
          f"pivot=origin  {status}")
    return tris <= budget


def make_lineup(previews, path, cols=5, cell=256):
    """Contact sheet of previews so a whole batch can be checked in one image."""
    rows = -(-len(previews) // cols)
    sheet = np.zeros((rows * cell, cols * cell, 4))
    sheet[..., 3] = 1
    for i, p in enumerate(previews):
        img = bpy.data.images.load(p)
        w, h = img.size
        px = np.array(img.pixels[:]).reshape(h, w, 4)[:: max(1, h // cell), :: max(1, w // cell)][:cell, :cell]
        r, c = rows - 1 - i // cols, i % cols
        sheet[r * cell:r * cell + px.shape[0], c * cell:c * cell + px.shape[1]] = px
    img = bpy.data.images.new("lineup", sheet.shape[1], sheet.shape[0])
    img.pixels.foreach_set(sheet.astype(np.float32).ravel())
    img.filepath_raw = path
    img.file_format = "PNG"
    img.save()
    print(f"[lineup] {path}")


def build(asset, out_dir):
    kind, _, aid = asset.partition(":")
    reset_scene()
    if kind == "fruit":
        obj, k = build_fruit(aid, out_dir)
    elif kind == "sword":
        obj, k = build_sword(aid, out_dir)
    else:
        raise SystemExit(f"unknown asset '{asset}'")
    return export(obj, k, out_dir), os.path.join(out_dir, obj.name + "_preview.png")


def expand(asset):
    if asset == "all":
        return expand("fruits") + expand("swords")
    if asset == "fruits":
        return ["fruit:" + f for f in FRUITS]
    if asset == "swords":
        return ["sword:" + s for s in SWORDS]
    return [asset]


def main():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else sys.argv[1:]
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--asset", default="all")
    parser.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "exports"))
    args = parser.parse_args(argv)
    out_dir = os.path.abspath(args.out)
    os.makedirs(out_dir, exist_ok=True)
    results = [build(a, out_dir) for a in expand(args.asset)]
    if len(results) > 1:
        make_lineup([p for _, p in results], os.path.join(out_dir, "_lineup.png"))
    if not all(ok for ok, _ in results):
        raise SystemExit("some assets are over their triangle budget")


if __name__ == "__main__":
    main()
