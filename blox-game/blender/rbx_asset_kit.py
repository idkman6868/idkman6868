def build_sword(sid, out_dir):
    s = SWORDS[sid]
    name = "Sword_" + "".join(p.capitalize() for p in sid.split("_"))
    colors = [s["blade"], s["edge"], s["guard"], s["handle"], s["pommel"]]
    px, uvs = swatch_texture(name, colors)
    img = make_image("T_" + name, px, out_dir)
    blade_uv, edge_uv, guard_uv, handle_uv, pommel_uv = uvs

    hl = s["handle_len"]
    guard_z = hl / 2 + 0.03
    parts = []

    # Blade: a curved, tapered strip. Back (spine) colored blade, front sliver colored edge.
    segs = 12
    L, W, T, C = s["blade_len"], s["blade_w"], 0.045, s["curve"]
    for part_uv, w0, w1 in ((blade_uv, -W / 2, W * 0.15), (edge_uv, W * 0.15, W / 2)):
        bm = bmesh.new()
        rings = []
        for i in range(segs + 1):
            t = i / segs
            z = guard_z + 0.03 + t * L
            off = C * t * t  # curve toward the edge side
            taper = 1.0 if t < 0.85 else max(0.0, 1 - (t - 0.85) / 0.15)
            a, b = w0 * taper + off, w1 * taper + off
            th = T * (0.5 if part_uv is edge_uv else 1.0) * max(taper, 0.15)
            ring = [bm.verts.new(p) for p in ((a, -th, z), (b, -th, z), (b, th, z), (a, th, z))]
            rings.append(ring)
        for r0, r1 in zip(rings, rings[1:]):
            for j in range(4):
                bm.faces.new((r0[j], r0[(j + 1) % 4], r1[(j + 1) % 4], r1[j]))
        bm.faces.new(list(reversed(rings[0])))
        bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-4)
        bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
        paint_uv(bm, part_uv)
        parts.append(bm_to_object(bm, name + "_blade"))

    def cyl(r1, r2, depth, z, uv, segments=8, sx=1.0):
        bm = bmesh.new()
        bmesh.ops.create_cone(bm, cap_ends=True, cap_tris=False, segments=segments,
                              radius1=r1, radius2=r2, depth=depth)
        bmesh.ops.scale(bm, vec=(sx, 1.0, 1.0), verts=bm.verts)
        bmesh.ops.translate(bm, vec=(0, 0, z), verts=bm.verts)
        paint_uv(bm, uv)
        return bm_to_object(bm, name + "_part")

    if s.get("guard_type") == "cross":
        bm = bmesh.new()
        bmesh.ops.create_cube(bm, size=1.0)
        bmesh.ops.scale(bm, vec=(s["guard_r"] * 4.0, 0.14, 0.14), verts=bm.verts)
        bmesh.ops.translate(bm, vec=(0, 0, guard_z), verts=bm.verts)
        paint_uv(bm, guard_uv)
        parts.append(bm_to_object(bm, name + "_guard"))
    else:
        parts.append(cyl(s["guard_r"], s["guard_r"], 0.06, guard_z, guard_uv, segments=10, sx=1.25))
    parts.append(cyl(0.075, 0.07, hl, 0.0, handle_uv, segments=8))
    parts.append(cyl(0.09, 0.07, 0.08, -hl / 2 - 0.04, pommel_uv, segments=8))

    obj = join(parts, name)
    obj.data.materials.append(make_material("M_" + name, img, roughness=0.35, metallic=0.6))
    for p in obj.data.polygons:
        p.use_smooth = False
    return obj, "sword"


