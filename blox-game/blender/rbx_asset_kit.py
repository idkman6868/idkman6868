"""Roblox asset kit: builds game-ready low-poly models in Blender from code.

Every asset is generated by a script, so it can be rebuilt, tweaked and re-exported at any time.
Each build writes, per asset:
    <out>/<Asset>.fbx          ready for the Roblox 3D Importer (texture embedded)
    <out>/T_<Asset>.png        the asset's color texture (for SurfaceAppearance / TextureID)
    <out>/<Asset>_preview.png  a rendered preview to check the model without opening Blender
    <out>/<Asset>.blend        editable source scene
and prints a report line (tris, size in studs, pivot).

Run with the Blender app:
    blender -b -P blox-game/blender/rbx_asset_kit.py -- --asset all --out blox-game/blender/exports
or with the `bpy` Python module (pip install bpy):
    python blox-game/blender/rbx_asset_kit.py --asset fruit:gomu_gomu --out blox-game/blender/exports

--asset accepts: all | fruits | swords | fruit:<id> | sword:<id>   (ids: gomu_gomu, mera_mera, enma, ...)
Units: 1 Blender unit = 1 Roblox stud. In the Roblox 3D Importer set File Dimensions to "Studs".
"""

