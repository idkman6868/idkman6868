SPHERE_V0 = 0.125  # sphere UVs use the top 7/8 of the texture; the bottom strip holds stem/leaf swatches


def fruit_texture(look, size=256):
    """Swirl pattern in equirectangular space with dark outlines on the stripes (anime look)."""
    base, swirls = hex_rgb(look["base"]), [hex_rgb(c) for c in look["swirls"]]
    arms, twist = look.get("arms", 3), look.get("twist", 1.5)
    px = np.ones((size, size, 4))
    sphere_rows = int(size * (1 - SPHERE_V0))
    strip = size - sphere_rows

    u = (np.arange(size) + 0.5) / size
    v = (np.arange(sphere_rows) + 0.5) / sphere_rows
    U, V = np.meshgrid(u, v)
    k = arms * U + twist * V  # arm coordinate: integer part picks the arm, fraction is position across it
    frac = k - np.floor(k)
    arm = np.floor(k).astype(int) % len(swirls)
    width = 0.34
    stripe = frac < width
    edge = stripe & ((frac < 0.035) | (frac > width - 0.035))

    img = np.broadcast_to(base, U.shape + (3,)).copy()
    for i, c in enumerate(swirls):
        img[stripe & (arm == i)] = c
    img[edge] = img[edge] * 0.55
    # soft vertical shading baked in: slightly darker toward the bottom
    img *= (0.82 + 0.18 * V)[..., None]
    px[strip:, :, :3] = img

    # bottom strip: stem (left half) and leaf (right half)
    px[:strip, : size // 2, :3] = hex_rgb(look["stem"])
    px[:strip, size // 2:, :3] = hex_rgb(look["leaf"])
    stem_uv = (0.25, SPHERE_V0 / 2)
    leaf_uv = (0.75, SPHERE_V0 / 2)
    return px, stem_uv, leaf_uv


def build_fruit(fid, out_dir):
    look = FRUITS[fid]
    name = "Fruit_" + "".join(p.capitalize() for p in fid.split("_"))
    radius = 0.8  # 1.6 stud diameter, readable in a player's hand
    squash, pear = look.get("squash", 1.0), look.get("pear", 0.0)
    lobes, lobe_depth = look.get("lobes", 0), look.get("lobe_depth", 0.0)
    heart = look.get("heart", 0.0)

    px, stem_uv, leaf_uv = fruit_texture(look)
    img = make_image("T_" + name, px, out_dir)

    # Body
    bm = bmesh.new()
    bm.loops.layers.uv.new()  # calc_uvs only fills an existing UV layer
    bmesh.ops.create_uvsphere(bm, u_segments=28, v_segments=16, radius=radius, calc_uvs=True)
    for vert in bm.verts:
        x, y, z = vert.co
        t = z / radius  # -1..1
        theta = math.atan2(y, x)
        r = 1.0
        if lobes:
            r += lobe_depth * math.cos(lobes * theta) * (1 - t * t)
        r *= 1 - pear * max(t, 0.0)
        z *= squash
        if heart:  # two bumps on top, a point at the bottom
            r *= 1 - 0.55 * heart * max(-t, 0.0) ** 1.3
            z *= 1 + 0.3 * heart * max(-t, 0.0)
            z -= heart * 0.35 * radius * max(t, 0.0) ** 2 * max(0.0, 1 - abs(x) / (radius * 0.55))
        z -= 0.10 * radius * max(t, 0.0) ** 10  # dimple where the stem sits
        vert.co = (x * r, y * r, z)
    uv = bm.loops.layers.uv.verify()
    for face in bm.faces:
        for loop in face.loops:
            uu, vv = loop[uv].uv
            loop[uv].uv = (uu, SPHERE_V0 + vv * (1 - SPHERE_V0))
    for face in bm.faces:
        face.smooth = True
    body = bm_to_object(bm, name + "_body")
    top = radius * squash * 0.9 - heart * 0.3 * radius

    # Stem: slightly bent, tapered
    bm = bmesh.new()
    bmesh.ops.create_cone(bm, cap_ends=True, cap_tris=False, segments=6, radius1=0.07, radius2=0.045, depth=0.42)
    paint_uv(bm, stem_uv)
    stem = bm_to_object(bm, name + "_stem")
    stem.location = (0.03, 0, top + 0.17)
    stem.rotation_euler = (0, math.radians(14), 0)

    # Leaf: flattened ellipsoid, a closed volume so it renders from both sides
    bm = bmesh.new()
    bmesh.ops.create_uvsphere(bm, u_segments=8, v_segments=4, radius=1.0)
    bmesh.ops.scale(bm, vec=(0.34, 0.14, 0.03), verts=bm.verts)
    paint_uv(bm, leaf_uv)
    leaf = bm_to_object(bm, name + "_leaf")
    leaf.location = (0.30, 0.02, top + 0.18)
    leaf.rotation_euler = (math.radians(10), math.radians(-28), math.radians(20))

    obj = join([body, stem, leaf], name)
    obj.data.materials.append(make_material("M_" + name, img, roughness=0.25))
    return obj, "fruit"


